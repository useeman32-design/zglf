function tryConnect($h,$u,$p,$db){
  try{return new PDO("mysql:host=$h;dbname=$db;charset=utf8mb4",$u,$p,[PDO::ATTR_ERRMODE=>PDO::ERRMODE_EXCEPTION,PDO::ATTR_DEFAULT_FETCH_MODE=>PDO::FETCH_ASSOC]);}catch(Exception $e){return null;}
}

